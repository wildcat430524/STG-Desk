const {app}=require('electron');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
process.argv.push('--smoke-test');
const smokePath=require.resolve('../electron/smoke.cjs');
require.cache[smokePath]={id:smokePath,filename:smokePath,loaded:true,exports:async win=>{
  const out=path.join(__dirname,'artifacts/answer-layout');await fs.mkdir(out,{recursive:true});
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'stg-answer-layout-'));
  await fs.cp(path.join(__dirname,'../demo/StepsToGreat'),root,{recursive:true});
  const base='我的学习/学科/Python/01-认识变量/';
  const guide=base+'01_教学引导.md',answer=base+'01_学生回答.md';
  const prompt='把下面这段用 Lambda 改写，并启动线程：\n\n```java\nRunnable task = new Runnable() {\n    @Override\n    public void run() {\n        System.out.println(Thread.currentThread().getName());\n    }\n};\nThread worker = new Thread(task);\nworker.start();\n```\n\n说明你的改写为什么符合 Runnable 接口的约定。';
  const questions='## 第二轮\n\n### 问题 3：用 Lambda 简化线程\n\n'+prompt+'\n\n**我的回答**\n\n### 问题 4：说明函数式接口\n\n什么是函数式接口？请结合 Runnable 说明。\n\n**我的回答**\n\n';
  const source='# Lambda 与 Stream · 学生回答\n\n'+questions+'## 最终复评结果\n\n（由导师填写）\n';
  await fs.writeFile(path.join(root,answer),source);
  await fs.writeFile(path.join(root,guide),'# Lambda 与 Stream\n\n'+questions.replaceAll('**我的回答**',''));
  const js=code=>win.webContents.executeJavaScript(code,true);
  const wait=async expr=>{for(let i=0;i<160;i++){if(await js(`document.documentElement.dataset.busy!=='true'&&(${expr})`))return;await new Promise(r=>setTimeout(r,75));}throw Error('UI wait failed: '+expr);};
  const capture=async(name,panel=false)=>{
    win.showInactive();await js("document.querySelector('#toast').classList.add('hidden')");await new Promise(r=>setTimeout(r,220));
    const rect=panel?await js("(()=>{const r=document.querySelector('#answers-panel').getBoundingClientRect();return {x:Math.ceil(r.x),y:Math.ceil(r.y),width:Math.floor(r.width),height:Math.floor(r.height)}})()"):undefined;
    await fs.writeFile(path.join(out,name),(await win.webContents.capturePage(rect)).toPNG());
  };
  const click=async selector=>{
    const point=await js(`(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
    win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});
    win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point});
    await new Promise(r=>setTimeout(r,100));
  };
  const input=async(selector,value)=>{await click(selector);await win.webContents.insertText(value);};
  const evidence=[];
  try{
    win.setSize(1460,960);
    await wait("!!document.querySelector('#welcome-import')");
    await js(`document.querySelector('#recent').innerHTML='<button id="recent-open">打开验收工作区</button>';document.querySelector('#recent-open').dataset.root=${JSON.stringify(root)};document.querySelector('#recent-open').click()`);
    await wait("!!document.querySelector('.file.selected')");
    await js(`document.querySelector('[data-file="${guide}"]').click()`);
    await wait("document.querySelectorAll('.question-card').length===2");
    assert.equal(await js("document.querySelectorAll('.question-card:not(.hidden)').length"),1);
    assert.equal(await js("document.querySelector('.answer-prompt').open"),false);
    const geometry=await js("(()=>{const rect=s=>{const r=document.querySelector(s).getBoundingClientRect();return {top:r.top,bottom:r.bottom,width:r.width,height:r.height}};return {panel:rect('#answers-panel'),heading:rect('.answer-heading'),tabs:rect('.answer-tabs'),nav:rect('#answer-question-nav'),content:rect('#answer-content'),input:rect('#answer-0'),footer:rect('#answer-footer')}})()");
    evidence.push({layout:geometry});
    await capture('workspace.png');await capture('answer-panel.png',true);
    assert.ok(geometry.input.height>=240);
    assert.ok(geometry.input.bottom<=geometry.footer.top,'Answer input should be visible above the save footer');
    assert.ok(geometry.heading.height+geometry.tabs.height+geometry.nav.height+geometry.footer.height<240);
    await click('.answer-prompt summary');
    assert.equal(await js("document.querySelector('.answer-prompt').open"),true);
    assert.equal(await js("getComputedStyle(document.querySelector('.question-prompt')).maxHeight"),'none');
    assert.equal(await js("getComputedStyle(document.querySelector('.question-prompt')).overflowY"),'visible');
    await click('.answer-prompt summary');
    await input('#answer-0','new Thread(() -> System.out.println("Lambda 验收")).start();');
    await click('[data-answer-question="1"]');
    await input('#answer-1','函数式接口只有一个抽象方法，Runnable 的抽象方法是 run。');
    await click('[data-answer-question="0"]');
    assert.ok(await js("document.querySelector('#answer-0').value.includes('Lambda 验收')"));
    await wait("document.querySelector('#draft-status').textContent==='草稿已自动保存'");
    const draft=await js(`window.stg.draftGet(${JSON.stringify(answer)})`);
    assert.equal(Object.values(draft.answers).length,2);
    win.webContents.reload();
    await wait("document.querySelector('#answer-0')?.value.includes('Lambda 验收')");
    assert.ok(await js("document.querySelector('#answer-1').value.includes('函数式接口只有一个抽象方法')"));
    assert.equal(await js("document.querySelectorAll('.answer-question-check').length"),2);
    assert.equal(await js("[...document.querySelectorAll('.answer-question-check')].every(s=>s.textContent==='✓')"),true);
    evidence.push('Native typing and question switching preserve both answer values in the local draft');
    await click('[data-answer-tab="records"]');
    assert.equal(await js("document.querySelector('#answer-question-nav').classList.contains('hidden')"),true);
    await click('[data-answer-tab="current"]');
    assert.ok(await js("document.querySelector('#answer-0').value.includes('Lambda 验收')"));
    await click('#answer-focus');
    assert.equal(await js("getComputedStyle(document.querySelector('#content-area')).display"),'none');
    await capture('focus.png');
    win.setSize(1050,760);await new Promise(r=>setTimeout(r,200));
    assert.notEqual(await js("getComputedStyle(document.querySelector('#answers-panel')).display"),'none');
    assert.equal(await js("document.documentElement.scrollWidth>innerWidth"),false);
    assert.equal(await js("(()=>{const input=document.querySelector('#answer-0').getBoundingClientRect(),footer=document.querySelector('#answer-footer').getBoundingClientRect();return input.bottom<=footer.top})()"),true,'Focused input should remain visible in a short window');
    await capture('focus-narrow.png');
    win.webContents.sendInputEvent({type:'keyDown',keyCode:'Escape'});win.webContents.sendInputEvent({type:'keyUp',keyCode:'Escape'});
    assert.equal(await js("document.body.classList.contains('answer-focused')"),false);
    assert.equal(await js("getComputedStyle(document.querySelector('#answers-panel')).display"),'none');
    win.setSize(1460,960);await new Promise(r=>setTimeout(r,200));
    await click('#app-theme-toggle');await capture('dark.png');await click('#app-theme-toggle');
    evidence.push('Focused answer mode expands at normal and narrow widths, exits with Escape, and supports dark theme');
    await click('#answer-focus');
    win.webContents.sendInputEvent({type:'keyDown',keyCode:'S',modifiers:['control']});
    win.webContents.sendInputEvent({type:'keyUp',keyCode:'S',modifiers:['control']});
    await wait("document.querySelector('#answer-0').value===''");
    const saved=await fs.readFile(path.join(root,answer),'utf8');
    assert.ok(saved.includes('Lambda 验收'));assert.ok(saved.includes('函数式接口只有一个抽象方法'));
    assert.ok(saved.includes('（由导师填写）'));
    evidence.push('Saving the round appends both answers including the hidden question and retains existing final review text');
    await fs.writeFile(path.join(out,'result.json'),JSON.stringify({passed:true,evidence,root},null,2));
    console.log(JSON.stringify({passed:true,out,evidence}));app.exit(0);
  }catch(error){await fs.writeFile(path.join(out,'result.json'),JSON.stringify({passed:false,error:error.stack,evidence,root},null,2));console.error(error);app.exit(1);}
}};
require('../electron/main.cjs');
